"""SQLite fallback and transactional, idempotent PostgreSQL migration for the demo."""
from contextlib import contextmanager
from pathlib import Path
import os
import sqlite3


class Database:
    def __init__(self):
        self.backend = os.environ.get('DATABASE_BACKEND', 'sqlite')
        if self.backend not in ('sqlite', 'postgres'):
            raise ValueError('Unsupported database backend')
        self.path = (Path(os.environ.get('DATA_DIR', '/data')) / 'demo.sqlite3').resolve()
        if self.backend == 'sqlite':
            self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as db:
            identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if self.backend == 'postgres' else 'INTEGER'
            db.execute(f'CREATE TABLE IF NOT EXISTS notes (id {identity} PRIMARY KEY, message TEXT NOT NULL, created TEXT NOT NULL)')
        if self.backend == 'postgres' and self.path.exists():
            self.import_sqlite()

    @contextmanager
    def connect(self):
        if self.backend == 'postgres':
            import psycopg
            # libpq PGHOST/PGDATABASE/PGUSER/PGPASSWORD/PGSSLMODE/PGSSLROOTCERT
            # come from Kubernetes Secrets and the operator's server CA.
            with psycopg.connect(connect_timeout=10) as db:
                yield db
        else:
            with sqlite3.connect(self.path, timeout=10) as db:
                yield db

    def import_sqlite(self):
        with sqlite3.connect(self.path.as_uri() + '?mode=ro', uri=True) as old:
            rows = old.execute('SELECT id, message, created FROM notes ORDER BY id').fetchall()
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(20261022)')
            db.execute('CREATE TABLE IF NOT EXISTS legacy_imports (source TEXT PRIMARY KEY, rows_imported BIGINT NOT NULL)')
            if db.execute("SELECT 1 FROM legacy_imports WHERE source='sqlite'").fetchone():
                return
            for row in rows:
                existing = db.execute('SELECT id, message, created FROM notes WHERE id=%s', (row[0],)).fetchone()
                if existing is not None and existing != row:
                    raise RuntimeError('Legacy note conflicts with PostgreSQL; migration rolled back')
                if existing is None:
                    db.execute('INSERT INTO notes(id,message,created) VALUES (%s,%s,%s)', row)
            db.execute("SELECT setval(pg_get_serial_sequence('notes','id'), COALESCE((SELECT MAX(id) FROM notes),0)+1, false)")
            db.execute("INSERT INTO legacy_imports(source,rows_imported) VALUES ('sqlite',%s)", (len(rows),))

    def health(self):
        with self.connect() as db:
            db.execute('SELECT 1').fetchone()

    def notes(self):
        with self.connect() as db:
            return db.execute('SELECT id,message,created FROM notes ORDER BY id DESC LIMIT 100').fetchall()

    def add(self, message, created):
        with self.connect() as db:
            if self.backend == 'postgres':
                return db.execute('INSERT INTO notes(message,created) VALUES (%s,%s) RETURNING id', (message, created)).fetchone()[0]
            return db.execute('INSERT INTO notes(message,created) VALUES (?,?)', (message, created)).lastrowid
